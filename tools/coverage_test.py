"""Coverage of the posterior intervals over noise realizations (synthetic test 3).

For each noise seed the data of ``examples/synthetic`` are regenerated by
``tools/make_synthetic_example.py --seed`` (seed 0 is the shipped data) and
inverted with all data groups. A calibrated posterior puts the truth inside
its 90 % interval in about 90 % of the realizations; with n seeds the count
has a binomial spread of sqrt(0.09 n).

    python tools/coverage_test.py examples/synthetic runs/coverage --seeds 20

Writes one directory per seed (data and run), ``summary.nc`` (quantiles per
seed and quantity, truth) and ``summary.md`` (coverage, and the mean offset of
the median from the truth in units of the 90 % half-width). Finished seeds are
not rerun.
"""

import argparse
import shutil
from pathlib import Path

import numpy as np
import xarray as xr
from data_subset_test import DERIVED, summarize
from make_synthetic_example import main as make_data
from make_synthetic_example import truth_of

from complybay.inference import derived_quantities
from complybay.io import load_yaml
from complybay.workflow import build_inversion, run_inversion


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("example", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--seeds", type=int, default=20)
    args = parser.parse_args(argv)
    args.output.mkdir(parents=True, exist_ok=True)
    seeds = list(range(args.seeds))
    for seed in seeds:
        run_dir = args.output / f"seed_{seed:02d}"
        if (run_dir / "posterior_mcmc.nc").exists():
            continue
        data_dir = run_dir / "data"
        data_dir.mkdir(parents=True, exist_ok=True)
        for name in ("model.yaml", "obs.yaml", "truth.yaml"):
            if (args.example / name).exists():
                shutil.copy(args.example / name, data_dir / name)
        make_data([str(data_dir), "--seed", str(seed)])
        print(f"running seed {seed}", flush=True)
        run_inversion(data_dir / "model.yaml", data_dir / "obs.yaml", run_dir, overwrite=True)

    p = build_inversion(load_yaml(args.example / "model.yaml")).parameterization
    values, _ = truth_of(args.example)
    truth = {**values, **derived_quantities(p.vector_to_model([values[n] for n in p.names]))}
    names = list(p.names) + DERIVED
    stats = np.array(
        [
            [
                summarize(args.output / f"seed_{s:02d}", "posterior", names, p)["stats"][n]
                for n in names
            ]
            for s in seeds
        ]
    )  # seed, quantity, (q05, median, q95, rhat)
    true = np.array([truth[n] for n in names])
    inside = (stats[..., 0] <= true) & (true <= stats[..., 2])
    half = 0.5 * (stats[..., 2] - stats[..., 0])
    offset = (stats[..., 1] - true) / half
    summary = xr.Dataset(
        {
            "q05": (("seed", "quantity"), stats[..., 0]),
            "median": (("seed", "quantity"), stats[..., 1]),
            "q95": (("seed", "quantity"), stats[..., 2]),
            "rhat": (("seed", "quantity"), stats[..., 3]),
            "truth": (("quantity",), true),
            "inside": (("seed", "quantity"), inside.astype(np.int8)),
        },
        coords={"seed": seeds, "quantity": names},
        attrs={"description": "90 % interval coverage over noise realizations, all data groups"},
    )
    summary.to_netcdf(args.output / "summary.nc", engine="h5netcdf")

    n = len(seeds)
    spread = np.sqrt(0.09 * n)
    lines = [
        f"{n} noise seeds; expected count inside the 90 % interval {0.9 * n:.1f} +- {spread:.1f}. "
        "Offset: mean (median - truth) / 90 % half-width (0 = unbiased).",
        "",
        "| quantity | inside | offset | max R-hat |",
        "|---|---|---|---|",
    ]
    for j, name in enumerate(names):
        rhat = np.nanmax(stats[:, j, 3]) if np.any(np.isfinite(stats[:, j, 3])) else np.nan
        count = int(inside[:, j].sum())
        lines.append(f"| {name} | {count} / {n} | {offset[:, j].mean():+.2f} | {rhat:.3f} |")
    text = "\n".join(lines) + "\n"
    (args.output / "summary.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
